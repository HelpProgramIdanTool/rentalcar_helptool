const assert=require('node:assert/strict');
const Selection=require('./static/partners/selection.js');
const selection=new Selection(['SUV-A','SUV-B','SUV-A','SUV-C']);
assert.equal(selection.set(2,true),true);
assert.deepEqual(selection.selectedIds(),['SUV-A']);
assert.deepEqual(selection.state(0),{checked:false,already:true,source:2});
assert.equal(selection.state(2).checked,true);
assert.equal(selection.set(0,true),false);
assert.equal(selection.set(0,false),true);
assert.equal(selection.state(2).checked,true);
selection.set(1,true);
assert.equal(selection.selectedIds().length,2);
selection.set(2,false);
assert.equal(selection.state(0).already,false);
assert.equal(selection.set(0,true),true);
assert.equal(selection.state(2).already,true);
const restored=new Selection(['A','A','B'],['A','A','B']);
assert.deepEqual(restored.selectedIds(),['A','B']);
assert.equal(restored.state(0).checked,true);
assert.equal(restored.state(1).already,true);
assert.equal(selection.set(99,true),false);
console.log('Unique selection: duplicates blocked, source preserved, removal unlocks duplicates, saved selections normalized.');
